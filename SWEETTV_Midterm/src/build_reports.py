def fi(n):
    return f"{n:,}" if isinstance(n, int) else str(n)


def fb(n):
    for unit in ["B", "KB", "MB", "GB"]:
        if n < 1024 or unit == "GB":
            return f"{n:,.2f} {unit}" if unit != "B" else f"{n:,} B"
        n /= 1024


def fp(part, whole, digits=2):
    if not whole:
        return "n/a"
    return f"{100.0 * part / whole:.{digits}f}%"


